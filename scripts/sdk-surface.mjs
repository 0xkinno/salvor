// Generates SDK_SURFACE.md: every outside call Salvor makes, with file:line, from the source itself.
// Line numbers can never go stale because the file is produced from the code. CI runs with --check.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const FILES = [
  ["Apify", "src/connectors/apify.ts", "apify-eyes"],
  ["TypeSafe Jev", "src/connectors/jev.ts", "jev-eyes"],
  ["Pinecone", "src/connectors/pinecone.ts", "pinecone-read / pinecone-write / pinecone-index-*"],
  ["Ollama Cloud", "src/connectors/ollama.ts", "ollama-hands"],
  ["Box", "src/connectors/box.ts", "box-hands"],
  ["AgentMail", "src/connectors/mail.ts", "mail-hands"],
  ["Fly Sprites API", "src/connectors/sprites.ts", "sprites-api-hands"],
];
const CALL = /\b(?:call|json)\(\s*[A-Za-z_"`][^,]*,\s*"(GET|POST|PUT|PATCH|DELETE)"\s*,\s*(`[^`]+`|"[^"]+"|[A-Za-z_][A-Za-z_0-9]*)/;
const CALL2 = /\bapi\(\s*"(GET|POST|PUT|PATCH|DELETE)"\s*,\s*(`[^`]+`|"[^"]+")/;
const SPRITE_ENV = /(sprite-env[^"\]]*|\/\.sprite\/[^"`]*)/;

let md = `# SDK_SURFACE.md

Generated by \`scripts/sdk-surface.mjs\` from the source. Every outside call Salvor makes, with its file and line.
Gateway base: \`https://api.sprites.dev/v1/gateway/<provider>/<connection_id>/<path>\`. No Authorization header is ever
sent from \`src/gateway.ts\` (it throws if one is passed).

Versions pinned in docs: Sprites API 0.1.12 (\`evidence/snapshots/fly-openapi.json\`), Jev 1.14 behind \`typesafe/jev\`
(\`jev-aimlapi.txt\`), Pinecone API version header \`2025-10\` (\`src/connectors/pinecone.ts\`), AgentMail \`/v0\`, Box \`/2.0\`,
Apify \`/v2\`, Ollama \`/api/chat\`.

`;
let total = 0;
for (const [name, file, conn] of FILES) {
  const lines = readFileSync(file, "utf8").split("\n");
  const rows = [];
  lines.forEach((ln, i) => {
    const m = CALL.exec(ln) ?? CALL2.exec(ln);
    if (m) rows.push(`| ${m[1]} | \`${/^[`"]/.test(m[2]) ? m[2].slice(1, -1).replace(/\$\{[^}]+\}/g, ":x") : "(" + m[2] + ", see the route list in the file)"}\` | \`${file}:${i + 1}\` |`);
  });
  total += rows.length;
  md += `## ${name}\n\nConnection: \`${conn}\`\n\n| Method | Path | Where |\n|---|---|---|\n${rows.join("\n")}\n\n`;
}
const env = [];
for (const f of ["src/receipt/evidence.ts", "src/receipt/worker.ts", "src/home/fleet.ts"]) {
  readFileSync(f, "utf8").split("\n").forEach((ln, i) => { if (/"sprite-env"|\/\.sprite\//.test(ln)) env.push(`| \`${f}:${i + 1}\` | ${ln.trim().slice(0, 110).replace(/\|/g, "/")} |`); });
}
md += `## Inside a Sprite (platform surfaces, not network calls)\n\n| Where | Line |\n|---|---|\n${env.join("\n")}\n`;

if (process.argv.includes("--check")) {
  if (!existsSync("SDK_SURFACE.md") || readFileSync("SDK_SURFACE.md", "utf8") !== md) { console.error("SDK_SURFACE.md is stale: run node scripts/sdk-surface.mjs"); process.exit(1); }
  console.log("sdk surface: up to date");
} else { writeFileSync("SDK_SURFACE.md", md); console.log(`SDK_SURFACE.md written, ${total} calls`); }
